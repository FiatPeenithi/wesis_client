/**
 * Get the appropriate NPC message based on days since quitting
 */
export function getStage5Message(daysSinceQuit: number): Stage5Message {
  const msg = stage5Messages.find(
    (m) => daysSinceQuit >= m.minDays && daysSinceQuit <= m.maxDays
  );
  // Fallback to the last message if days exceed all ranges
  return msg || stage5Messages[stage5Messages.length - 1];
}
